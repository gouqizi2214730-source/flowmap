import { expect, test } from '@playwright/test';

test('market desk has persistent layouts and resizes the aligned chart without resetting its stream', async ({ page }) => {
  const errors: string[] = [];
  page.on('pageerror', error => errors.push(error.message));
  await page.addInitScript(() => {
    if (!localStorage.getItem('flowmap.active-symbol.v1')) localStorage.setItem('flowmap.active-symbol.v1', JSON.stringify({ market: 'sim', symbol: 'SIM-DEMO' }));
  });
  await page.goto('/?scrollback=1&budget=512');
  await page.waitForFunction(() => window.__flowmapLive?.renderer.marketFrameReady);
  await expect(page.getByTestId('orderflow-panel')).toBeVisible();
  await expect(page.getByTestId('flow-count')).not.toHaveText('—');
  const session = await page.evaluate(() => window.__flowmapLive!.store.getState().sessionId);
  await page.getByTestId('desk-layout-analysis').click();
  await expect(page.getByTestId('desk-layer-profile')).toHaveAttribute('aria-pressed', 'true');
  const canvasWidth = await page.locator('#gl').evaluate(el => el.clientWidth);
  const separator = page.locator('[role="separator"][aria-orientation="vertical"]');
  await separator.focus();
  await page.keyboard.press('ArrowRight');
  await page.keyboard.press('ArrowRight');
  await expect(separator).toHaveAttribute('aria-valuenow', '372');
  await expect.poll(() => page.locator('#gl').evaluate(el => el.clientWidth)).toBeLessThan(canvasWidth);
  const railBox = await separator.boundingBox();
  expect(railBox).not.toBeNull();
  await page.mouse.move(railBox!.x + railBox!.width / 2, railBox!.y + railBox!.height / 2);
  await page.mouse.down(); await page.mouse.move(railBox!.x + railBox!.width / 2 - 32, railBox!.y + railBox!.height / 2); await page.mouse.up();
  await expect(separator).toHaveAttribute('aria-valuenow', '404');
  await separator.focus(); await page.keyboard.press('ArrowLeft'); await page.keyboard.press('ArrowLeft');
  await expect(separator).toHaveAttribute('aria-valuenow', '372');
  const cvdSeparator = page.getByRole('separator', { name: 'Resize CVD pane' });
  const cvdBox = await cvdSeparator.boundingBox();
  expect(cvdBox).not.toBeNull();
  await page.mouse.move(cvdBox!.x + cvdBox!.width / 2, cvdBox!.y + cvdBox!.height / 2);
  await page.mouse.down(); await page.mouse.move(cvdBox!.x + cvdBox!.width / 2, cvdBox!.y + cvdBox!.height / 2 - 24); await page.mouse.up();
  await expect(cvdSeparator).toHaveAttribute('aria-valuenow', '184');
  const cvdLayout = await page.evaluate(() => {
    const stage = document.querySelector('.stage')!.getBoundingClientRect();
    const cvd = document.querySelector('.cvd-pane')!.getBoundingClientRect();
    const time = document.querySelector('.timeline')!.getBoundingClientRect();
    return { cvdBottom: cvd.bottom, stageBottom: stage.bottom, timelineTop: time.top, height: cvd.height };
  });
  expect(cvdLayout.cvdBottom).toBeLessThanOrEqual(cvdLayout.stageBottom - 20);
  expect(cvdLayout.cvdBottom).toBeLessThanOrEqual(cvdLayout.timelineTop);
  expect(cvdLayout.height).toBe(184);
  const bookSeparator = page.getByRole('separator', { name: 'Resize book and tape panels' });
  const bookBox = await bookSeparator.boundingBox();
  expect(bookBox).not.toBeNull();
  await page.mouse.move(bookBox!.x + bookBox!.width / 2, bookBox!.y + bookBox!.height / 2);
  await page.mouse.down(); await page.mouse.move(bookBox!.x + bookBox!.width / 2, bookBox!.y + bookBox!.height / 2 + 24); await page.mouse.up();
  expect(Number(await bookSeparator.getAttribute('aria-valuenow'))).toBeGreaterThan(.4);
  expect(await page.evaluate(() => window.__flowmapLive!.store.getState().sessionId)).toBe(session);
  await page.getByTestId('desk-layout-focus').click();
  await expect(page.getByTestId('right-rail')).toHaveCount(0);
  await expect(page.getByTestId('desk-layer-cvd')).toHaveAttribute('aria-pressed', 'false');
  await page.reload();
  await expect(page.getByTestId('desk-layout-focus')).toHaveAttribute('aria-pressed', 'true');
  await expect(page.getByTestId('right-rail')).toHaveCount(0);
  await page.getByTestId('desk-layout-orderflow').click();
  await expect(page.getByTestId('right-rail')).toBeVisible();
  await expect(separator).toHaveAttribute('aria-valuenow', '372');
  await page.waitForFunction(() => window.__flowmapLive?.renderer.marketFrameReady);
  await expect(page.getByTestId('market-last')).not.toHaveText('—');
  await expect(page.getByTestId('chart-startup-gate')).toHaveCount(0);
  expect(await page.getByTestId('tape-body').evaluate(el => el.clientHeight)).toBeGreaterThan(20);
  await expect(page.getByTestId('tape-row').first()).toBeVisible();
  await page.screenshot({ path: 'C:/Users/Kullanıcı/Documents/Codex/2026-10-04/sen/outputs/terminal-desk-preview.png' });
  expect(errors).toEqual([]);
});
